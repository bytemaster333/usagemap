// Evidence writer (ADR-0026: every layer writes machine-readable results and a Markdown summary to docs/evidence/).
// Files (append-only): docs/evidence/<layer>/<name>-<YYYYMMDDTHHMMSSZ>-<commit12>[-dirty].json and .md.
// A file is created exclusively (`wx`) and never overwritten; two runs never share a name. A run from a tree with
// uncommitted changes is still written but carries `-dirty` in the name and `dirty: true` in both files, so it can
// never be mistaken for evidence of a commit; SCF_EVIDENCE_REQUIRE_CLEAN=1 refuses to write it at all. Only
// results of real runs are written — the callers pass what was measured; nothing here invents a number. Each file
// states the commit, the environment and which checks did not run and why.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "./env.ts";

export interface Check {
  name: string;
  outcome: "pass" | "fail" | "not_run";
  detail?: string;
  /** Capability ids (docs/capabilities.md) this check evidences. */
  ids?: string[];
}

export interface Evidence {
  layer: string;
  name: string;
  title: string;
  /** One paragraph: what ran, against what. */
  summary: string;
  checks: Check[];
  /** Measured figures (free-form, JSON-serialisable). */
  data?: unknown;
  /** Markdown appended after the checks table (tables of measurements, notes). */
  notes?: string;
}

function git(args: string[]): string {
  try {
    return execFileSync("git", args, { cwd: REPO_ROOT, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

/** Commit and cleanliness of the tree the run was made from. */
export interface TreeState {
  commit: string;
  dirty: boolean;
}

export function treeState(): TreeState {
  // Evidence files written earlier in the same run (docs/evidence/) do not make the tree dirty: otherwise the second
  // suite of a run that writes into the checkout would mark its evidence dirty because of the first suite's file.
  const status = git([
    "status",
    "--porcelain",
    "--untracked-files=normal",
    "--",
    ".",
    ":(exclude)docs/evidence",
  ]);
  return { commit: git(["rev-parse", "--short=12", "HEAD"]), dirty: status !== "" };
}

export function environment(tree: TreeState = treeState()): Record<string, string> {
  return {
    commit: tree.commit,
    dirty: tree.dirty ? "yes (uncommitted changes in the tree)" : "no",
    node: process.version,
    runner: process.env.CI ? "CI" : "local Docker host",
    os: `${process.platform}/${process.arch}`,
  };
}

function cell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function renderMarkdown(e: Evidence, at: Date, env: Record<string, string>): string {
  const counts = { pass: 0, fail: 0, not_run: 0 };
  for (const c of e.checks) counts[c.outcome]++;
  const lines = [
    `# ${e.title}`,
    "",
    `- **Run:** ${at.toISOString()} · commit \`${env.commit}\` (dirty: ${env.dirty}) · Node ${env.node} · ${env.os} · ${env.runner}`,
    ...(env.dirty?.startsWith("yes")
      ? [
          "- **Dirty tree:** this run was made with uncommitted changes; it is not evidence of commit " +
            `\`${env.commit}\` as such.`,
        ]
      : []),
    `- **Result:** ${counts.pass} passed, ${counts.fail} failed, ${counts.not_run} not run`,
    "",
    e.summary,
    "",
    "| Check | Outcome | Detail | IDs |",
    "|---|---|---|---|",
    ...e.checks.map(
      (c) =>
        `| ${cell(c.name)} | ${c.outcome === "pass" ? "PASS" : c.outcome === "fail" ? "**FAIL**" : "NOT RUN"} | ${cell(c.detail ?? "")} | ${(c.ids ?? []).join(", ")} |`,
    ),
    "",
  ];
  if (e.notes) lines.push(e.notes, "");
  lines.push(
    "_Generated by `tests/` from a real run; the JSON file next to this one holds the raw figures._",
    "",
  );
  return lines.join("\n");
}

/** UTC timestamp of a file name: 2026-11-13T09:05:01.123Z → 20261113T090501Z. */
export function stamp(at: Date): string {
  return `${at.toISOString().slice(0, 19).replace(/[-:]/g, "")}Z`;
}

/** File stem of an evidence run: <name>-<stamp>-<commit>[-dirty]. */
export function evidenceStem(name: string, at: Date, tree: TreeState): string {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) throw new Error(`evidence name ${JSON.stringify(name)}`);
  const commit = /^[0-9a-f]{7,40}$/.test(tree.commit) ? tree.commit : "nocommit";
  return `${name}-${stamp(at)}-${commit}${tree.dirty ? "-dirty" : ""}`;
}

export function writeEvidence(
  dir: string,
  e: Evidence,
  at = new Date(),
  tree: TreeState = treeState(),
): { json: string; md: string } {
  if (tree.dirty && process.env.SCF_EVIDENCE_REQUIRE_CLEAN === "1")
    throw new Error(
      "evidence refused: the tree has uncommitted changes (SCF_EVIDENCE_REQUIRE_CLEAN=1)",
    );
  const env = environment(tree);
  const base = join(dir, e.layer);
  mkdirSync(base, { recursive: true });
  const stem = evidenceStem(e.name, at, tree);
  const json = join(base, `${stem}.json`);
  const md = join(base, `${stem}.md`);
  // `wx`: exclusive create — an existing file is never overwritten (EEXIST is thrown instead).
  writeFileSync(
    json,
    `${JSON.stringify({ ...e, at: at.toISOString(), commit: tree.commit, dirty: tree.dirty, environment: env }, null, 2)}\n`,
    { flag: "wx" },
  );
  writeFileSync(md, renderMarkdown(e, at, env), { flag: "wx" });
  return { json, md };
}

/** Reads the gate decisions recorded during this run (lib/gate.ts) as not-run checks. */
export function gateChecks(workDir: string): Check[] {
  const f = join(workDir, "gates.jsonl");
  if (!existsSync(f)) return [];
  return readFileSync(f, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l) as { test: string; missing: { cap: string; detail: string }[] })
    .map((g) => ({
      name: g.test,
      outcome: "not_run" as const,
      detail: `requires: ${g.missing.map((m) => `${m.cap} (${m.detail})`).join("; ")}`,
    }));
}
