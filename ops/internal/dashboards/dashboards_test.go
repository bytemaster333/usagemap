// The committed JSON in ops/dashboards must be exactly what the code renders.
func TestCommittedDashboardsMatchCode(t *testing.T) {
	dir := filepath.Join("..", "..", "dashboards")
	seen := map[string]bool{}
	for _, d := range All() {
		want, err := JSON(d)
		if err != nil {
			t.Fatal(err)
		}
		got, err := os.ReadFile(filepath.Join(dir, FileName(d)))
		if err != nil || !bytes.Equal(got, want) {
			t.Errorf("%s differs from the code: run `go run ./cmd/scf-ops dashboards -out dashboards` in ops/", FileName(d))
		}
		seen[FileName(d)] = true
	}
	files, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	for _, f := range files {
		if !seen[filepath.Base(f)] {
			t.Errorf("%s is not generated by the code", f)
		}
	}
}

func TestPlanDashboardsPresentAndPrivacy(t *testing.T) {
	all := All()
	if len(all) != 14 {
		t.Fatalf("%d dashboards, want D1–D14", len(all))
	}
	uids := map[string]bool{}
	forbidden := regexp.MustCompile(`(?i)(by \([^)]*|\{\{\s*|[{,]\s*)(tenant\w*|site\w*|path|url|ip|address|user_agent|ua|token|session)\b`)
	for i, d := range all {
		if !strings.HasPrefix(d.Title, "D"+itoa(i+1)+" ") || uids[d.UID] || len(d.UID) > 40 {
			t.Errorf("dashboard %d: title %q / uid %q", i+1, d.Title, d.UID)
		}
		uids[d.UID] = true
		for _, p := range d.Panels {
			for _, q := range p.Queries {
				if forbidden.MatchString(q.Expr) || forbidden.MatchString(q.Legend) {
					t.Errorf("%s / %s: query touches a personal or tenant dimension: %s", d.Title, p.Title, q.Expr)
				}
			}
		}
	}
}

func itoa(i int) string { return strconv.Itoa(i) }
