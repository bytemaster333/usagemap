// Generates the external status checks from ops/status/sli.json (core plan C1 item 5; slo.ingest-availability, slo.dashboard-availability):
//   gatus/config.yaml        Gatus v5.38.0 (ADR-0022): 30-second checks from an independent vantage point
//   upptime/.upptimerc.yml   Upptime (DV-06): 5-minute checks from GitHub-hosted runners, the public status page
//
//   node ops/status/generate.ts           write both files
//   node ops/status/generate.ts --check   exit 1 when a committed file differs from what sli.json generates

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HERE = import.meta.dirname;

interface Check {
  id: string;
  env: string;
  path: string;
  status: number[];
  bodyField?: string;
  bodyValue?: string;
}
export interface Sli {
  coverageFloor: number;
  objectives: Record<string, { ingest: number; dashboard: number }>;
  ingest: {
    hosts: { id: string; env: string }[];
    path: string;
    status: number[];
    bodyField: string;
    bodyValue: string;
    maxResponseMs: number;
  };
  dashboard: { portal: Check; api: Check; maxStepMs: number };
  vantagePoints: { id: string; tool: string; intervalSeconds: number; where: string }[];
}

export function loadSli(file = join(HERE, "sli.json")): Sli {
  return JSON.parse(readFileSync(file, "utf8")) as Sli;
}

/** Every external check, in page order. */
export function checks(s: Sli): (Check & { group: string; maxMs: number })[] {
  return [
    ...s.ingest.hosts.map((h) => ({
      id: h.id,
      env: h.env,
      path: s.ingest.path,
      status: s.ingest.status,
      bodyField: s.ingest.bodyField,
      bodyValue: s.ingest.bodyValue,
      group: "ingest",
      maxMs: s.ingest.maxResponseMs,
    })),
    { ...s.dashboard.portal, group: "dashboard", maxMs: s.dashboard.maxStepMs },
    { ...s.dashboard.api, group: "dashboard", maxMs: s.dashboard.maxStepMs },
  ];
}

const HEADER = (what: string): string =>
  `# SPDX-License-Identifier: Apache-2.0\n# GENERATED by ops/status/generate.ts from ops/status/sli.json — do not edit; run \`node ops/status/generate.ts\`.\n# ${what}\n`;

export function gatus(s: Sli): string {
  const vp = s.vantagePoints.find((v) => v.tool === "gatus");
  if (!vp) throw new Error("sli.json: no gatus vantage point");
  const L: string[] = [
    HEADER(
      "Gatus at an independent vantage point (ops/status/README.md). Base URLs come from the environment, e.g. SCF_STATUS_INGEST_URL_A=https://<ingest host A>.",
    ),
    "storage:",
    "  type: sqlite",
    "  path: /data/gatus.db",
    "web:",
    "  port: 8080",
    "ui:",
    "  title: UsageMap external checks",
    "  header: UsageMap external checks",
    "endpoints:",
  ];
  for (const c of checks(s)) {
    L.push(
      `  - name: ${c.id}`,
      `    group: ${c.group}`,
      `    url: "\${${c.env}}${c.path}"`,
      `    interval: ${vp.intervalSeconds}s`,
      "    client:",
      // The timeout is the threshold itself: a slower answer is a failed check, never a wait.
      `      timeout: ${c.maxMs}ms`,
      "    conditions:",
      c.status.length === 1
        ? `      - "[STATUS] == ${c.status[0]}"`
        : `      - "[STATUS] == any(${c.status.join(", ")})"`,
      ...(c.bodyField ? [`      - "[BODY].${c.bodyField} == ${c.bodyValue}"`] : []),
      `      - "[RESPONSE_TIME] < ${c.maxMs}"`,
    );
  }
  return `${L.join("\n")}\n`;
}

export function upptime(s: Sli): string {
  const L: string[] = [
    HEADER(
      "Upptime configuration for the status repository ORG/status (DV-06): copy to its root as .upptimerc.yml. Base URLs are repository secrets of ORG/status (Upptime `$SECRET` syntax).",
    ),
    "owner: ORG",
    "repo: status",
    "user-agent: ORG",
    "sites:",
  ];
  for (const c of checks(s)) {
    L.push(
      `  - name: ${c.id}`,
      `    url: $${c.env}${c.path}`,
      "    expectedStatusCodes:",
      ...c.status.map((x) => `      - ${x}`),
      `    maxResponseTime: ${c.maxMs}`,
    );
    if (c.bodyField && c.bodyValue) {
      const key = c.bodyField.split(".").at(-1) as string;
      L.push(`    __dangerous__body_down_if_text_missing: '"${key}":"${c.bodyValue}"'`);
    }
  }
  L.push(
    "secrets:",
    ...[...new Set(checks(s).map((c) => c.env))].map((e) => `  - ${e}`),
    "status-website:",
    "  cname: status.<domain-a>",
    "  name: UsageMap status",
    "  introTitle: UsageMap service status",
    "  introMessage: Checks every 5 minutes from GitHub-hosted runners, outside our infrastructure. This page is a public cross-check; the availability figures are in the monthly SLO report (docs/sla.md §7).",
    "  navbar:",
    "    - title: Status",
    "      href: /",
    "    - title: SLO reports",
    "      href: https://github.com/ORG/REPO/tree/main/docs/evidence/slo",
  );
  return `${L.join("\n")}\n`;
}

export function outputs(s = loadSli()): Record<string, string> {
  return {
    [join(HERE, "gatus", "config.yaml")]: gatus(s),
    [join(HERE, "upptime", ".upptimerc.yml")]: upptime(s),
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [f, body] of Object.entries(outputs())) {
    let cur = "";
    try {
      cur = readFileSync(f, "utf8");
    } catch {}
    if (cur === body) continue;
    if (check) {
      process.stdout.write(`STALE ${f}\n`);
      stale++;
    } else {
      writeFileSync(f, body);
      process.stdout.write(`wrote ${f}\n`);
    }
  }
  process.exit(stale ? 1 : 0);
}
