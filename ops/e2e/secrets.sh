# Creates the monitoring overlay's development secrets in infra/compose/.secrets/ (git-ignored) when missing, with the
# same conventions as infra/compose/scripts/dev-secrets.sh (directory 0700, files 0644 so the containers' users can read
# the bind mounts). Never replaces an existing value. A candidate for folding into dev-secrets.sh.
set -euo pipefail
OUT="$(cd "$(dirname "$0")/../../infra/compose" && pwd)/.secrets"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
mkdir -p "$OUT" && chmod 700 "$OUT"
rnd() { openssl rand -hex 32; }
for f in grafana_admin_password heartbeat_token dns_token; do
  [[ -s "$OUT/$f" ]] || { rnd >"$OUT/$f"; echo "created $f"; }
done
if [[ ! -s "$OUT/journey_seed" ]]; then
  # A dedicated Stellar keypair for the synthetic journey member (never a real user, C-93). Generated by scf-ops in a
  # container without network; the seed only ever lives in this file.
  docker image inspect usagemap/ops:dev >/dev/null 2>&1 || docker build -q -f "$ROOT/ops/Dockerfile" -t usagemap/ops:dev "$ROOT" >/dev/null
  docker run --rm --network none --read-only --cap-drop ALL --user "$(id -u):$(id -g)" -v "$OUT:/out" usagemap/ops:dev \
    keygen -seed-file /out/journey_seed >/dev/null
  echo "created journey_seed"
fi
chmod 644 "$OUT"/grafana_admin_password "$OUT"/heartbeat_token "$OUT"/dns_token "$OUT"/journey_seed
