// Writes src/lib/definitions.gen.ts from docs/metrics/definitions.md (plus src/lib/metric-definitions.pending.md, rows
// not in the document yet): the definition shown on every metric card of the portal.
// Every metric key the portal uses (`data-metric`, `<MetricTile metric=…>`) maps here to one bold figure name of a
// definitions table; a key whose figure is missing fails the build. `--check` fails when the committed file is stale
// (run by `pnpm test`); `pnpm build` regenerates it first.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..", "..");
const DOC = "docs/metrics/definitions.md";
const PENDING = "apps/portal/src/lib/metric-definitions.pending.md";
const OUT = join(here, "..", "src", "lib", "definitions.gen.ts");

