export interface Definition {
  term: string;
  text: string;
  /** "docs/metrics/definitions.md §2.2 Totals" */
  source: string;
}

/** Markdown inline → plain text (code spans, emphasis and links dropped to their text). */
export function plain(md: string): string {
  return md
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/(^|[^*])\*([^*]+)\*/g, "$1$2")
    .replace(/\s+/g, " ")
    .trim();
}

/** Every table row whose first cell starts with a bold figure name: term → definition (second cell). */
export function parseDefinitions(md: string, file: string): Map<string, Definition> {
  const out = new Map<string, Definition>();
  let heading = "";
  for (const line of md.split("\n")) {
    const h = /^#{2,4} (.+)$/.exec(line);
    if (h) {
      heading = plain(h[1] as string);
      continue;
    }
    const m = /^\| \*\*([^*]+)\*\*[^|]*\| ([^|]+) \|/.exec(line);
    if (!m) continue;
    const term = (m[1] as string).trim();
    if (out.has(term)) throw new Error(`${file}: "${term}" is defined twice`);
    out.set(term, { term, text: plain(m[2] as string), source: `${DOC} §${heading}` });
  }
  return out;
}

export function render(doc: string, pending: string): string {
  const defs = parseDefinitions(doc, DOC);
  for (const [term, d] of parseDefinitions(pending, PENDING)) {
    if (defs.has(term))
      throw new Error(`"${term}" is in ${DOC} now: delete its row from ${PENDING}`);
    defs.set(term, d);
  }
  const entries: Record<string, Definition> = {};
  for (const [key, term] of Object.entries(METRIC_TERMS)) {
    const d = defs.get(term);
    if (!d) throw new Error(`metric ${key}: no definition of "${term}" in ${DOC} or ${PENDING}`);
    entries[key] = d;
  }
  return [
    "// Code generated by apps/portal/scripts/gen-definitions.ts from docs/metrics/definitions.md. DO NOT EDIT.",
    "",
    "export interface MetricDefinition {",
    "  term: string;",
    "  text: string;",
    "  source: string;",
    "}",
    "",
    `export const METRIC_DEFINITIONS = ${JSON.stringify(entries, null, 2)} as const satisfies Record<string, MetricDefinition>;`,
    "",
    "export type MetricKey = keyof typeof METRIC_DEFINITIONS;",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = render(
    readFileSync(join(repo, DOC), "utf8"),
    readFileSync(join(repo, PENDING), "utf8"),
  );
  let have = "";
  try {
    have = readFileSync(OUT, "utf8");
  } catch {
    // first run
  }
  if (process.argv.includes("--check")) {
    if (have !== want) {
      console.error(`${OUT} is stale: run node scripts/gen-definitions.ts`);
      process.exitCode = 1;
    }
  } else if (have !== want) {
    writeFileSync(OUT, want);
    console.log(`wrote ${OUT}`);
  }
}
