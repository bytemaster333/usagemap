// Writes server/headers-http.caddy and server/headers-https.caddy from server/headers.ts, the single source of the
// portal's security headers. `--check` fails when the committed files are stale (run by `pnpm test`).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type Scheme, securityHeaders } from "../server/headers.ts";

const serverDir = join(dirname(fileURLToPath(import.meta.url)), "..", "server");

export function renderCaddySnippet(scheme: Scheme): string {
  const lines = [
    "# Code generated by apps/portal/scripts/gen-caddy.ts from apps/portal/server/headers.ts. DO NOT EDIT.",
    `# Security headers for a portal served over ${scheme} (imported by server/Caddyfile).`,
    "header {",
    "\tdefer",
    "\t-Server",
    "\t-X-Powered-By",
  ];
  for (const [name, value] of Object.entries(securityHeaders(scheme))) {
    if (value.includes('"')) throw new Error(`header ${name} must not contain a double quote`);
    lines.push(`\t${name} "${value}"`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

const check = process.argv.includes("--check");
let stale = false;
for (const scheme of ["http", "https"] as const) {
  const file = join(serverDir, `headers-${scheme}.caddy`);
  const want = renderCaddySnippet(scheme);
  if (check) {
    let have = "";
    try {
      have = readFileSync(file, "utf8");
    } catch {
      // missing counts as stale
    }
    if (have !== want) {
      console.error(`${file} is stale: run pnpm --filter @usagemap/portal gen:caddy`);
      stale = true;
    }
  } else {
    writeFileSync(file, want);
  }
}
if (stale) process.exit(1);
