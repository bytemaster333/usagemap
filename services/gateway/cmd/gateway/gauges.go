func b2f(b bool) float64 {
	if b {
		return 1
	}
	return 0
}

func registerGauges(r *metrics.Registry, store *snapshot.Store, ring *keys.Ring, kx *keys.Exchange, sp *spool.Spool,
	mult *multiplicity.Store, ncls *netclass.Classifier, started time.Time, cfg *config.Config, limited func(time.Time) map[string]int) {
	r.GaugeFunc(func(emit func(string, string, float64)) {
		now := time.Now()
		age := store.Age(now, started)
		emit("scf_gateway_snapshot_sequence", "", float64(store.Sequence()))
		emit("scf_gateway_snapshot_age_seconds", "", age.Seconds())
		emit("scf_gateway_snapshot_stale", "", b2f(age > StaleAfter))
		emit("scf_gateway_snapshot_rollback_refused_total", "", float64(store.Rollbacks()))
		cur := store.Current()
		if exp, ok := cur.ExpiresAtOK(); ok {
			emit("scf_gateway_snapshot_expires_in_seconds", "", exp.Sub(now).Seconds())
		}
		emit("scf_gateway_snapshot_expired", "", b2f(cur.Expired(now)))
		for reason, n := range store.Failures() {
			emit("scf_gateway_snapshot_verify_failures", metrics.Labels("reason", reason), float64(n))
		}
		st := sp.Stats()
		emit("scf_gateway_spool_events", metrics.Labels("counter", "fsynced"), float64(st.Totals.Fsynced))
		emit("scf_gateway_spool_events", metrics.Labels("counter", "acked_stored"), float64(st.Totals.AckedStored))
		emit("scf_gateway_spool_events", metrics.Labels("counter", "acked_engine_bot"), float64(st.Totals.AckedEngineBot))
		emit("scf_gateway_spool_events", metrics.Labels("counter", "acked_engine_rejected"), float64(st.Totals.AckedEngineRejected))
		emit("scf_gateway_spool_events", metrics.Labels("counter", "expired_72h"), float64(st.Totals.Expired72h))
		emit("scf_gateway_spool_queued", "", float64(st.Queued))
		emit("scf_gateway_spool_pending", "", float64(st.Pending))
		if st.OldestMs > 0 {
			emit("scf_gateway_spool_oldest_age_seconds", "", now.Sub(time.UnixMilli(st.OldestMs)).Seconds())
		} else {
			emit("scf_gateway_spool_oldest_age_seconds", "", 0)
		}
		emit("scf_gateway_spool_bytes", "", float64(st.Bytes))
		emit("scf_gateway_spool_segments", "", float64(st.Segments))
		emit("scf_gateway_spool_durable", "", b2f(sp.Durable()))
		emit("scf_gateway_spool_corrupt_frames", "", float64(st.Corrupt))
		emit("scf_gateway_spool_corrupt_bytes", "", float64(st.CorruptBytes))
		emit("scf_gateway_keys_held", "", float64(ring.Count()))
		emit("scf_gateway_keys_mlocked", "", b2f(ring.Locked()))
		emit("scf_gateway_core_dumps_disabled", "", b2f(secmem.CoreDumpsDisabled()))
		emit("scf_gateway_keys_current", "", b2f(ring.HasCurrent()))
		for _, k := range keys.Kinds {
			emit("scf_gateway_keyx_conflicts", metrics.Labels("kind", string(k)), float64(ring.Conflicts(k)))
		}
		emit("scf_gateway_live_edge_nodes", "", float64(kx.LiveNodes()))
		emit("scf_gateway_multiplicity_cells", "", float64(mult.Len()))
		emit("scf_gateway_multiplicity_evicted", "", float64(mult.Evicted()))
		for c, n := range ncls.Counts() {
			emit("scf_gateway_rangelist_entries", metrics.Labels("class", c), float64(n))
		}
		emit("scf_gateway_spool_max_bytes", "", float64(cfg.SpoolMaxBytes))
		if limited != nil {
			for kind, n := range limited(now) {
				emit("scf_gateway_sites_limited", metrics.Labels("kind", kind), float64(n))
			}
		}
		emit("scf_gateway_kday_regenerated_total", "", float64(kx.Stats().KDayRegenerated))
		if fp := ring.PublicFingerprintOf(keys.Day, keys.DayID(now)); fp != "" {
			emit("scf_gateway_kday_fingerprint_info", metrics.Labels("fingerprint", fp), 1)
		}
		emit("scf_gateway_start_time_seconds", "", float64(started.Unix()))
	})
}
