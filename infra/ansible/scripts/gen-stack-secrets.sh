# Production secrets of the lean profile (C-123, C-79) — the production counterpart of
# infra/compose/scripts/dev-secrets.sh, which is never used for a deployment. Run ONCE on a service-operator
# workstation; the output is plaintext YAML that must go straight into SOPS and nowhere else:
#
#   infra/ansible/scripts/gen-stack-secrets.sh --age-recipient age1… \
#     | sops --encrypt --input-type yaml --output-type yaml --age <team recipients> /dev/stdin > infra/ansible/group_vars/app.sops.yaml
#   (or -o FILE: writes FILE with mode 0600 and refuses to overwrite an existing one)
#
# Values: random hex passwords (URL-safe), APP_SECRET, versioned key sets `1:<base64 of 32 bytes>`, two Ed25519 signing
# keys (PKCS#8 PEM, openssl), two Stellar secret seeds (SEP-10 server key, synthetic journey member — StrKey computed
# here with the Python standard library), the pgBackRest cipher passes, the CA key passphrase and the OpenTofu state
# passphrase. The age RECIPIENT (public key) of the weekly logical dumps is an input: its identity stays offline with
# the operating team. Nothing is printed to the terminal except to stdout as requested.
set -euo pipefail
usage() { echo "usage: $0 --age-recipient age1… [-o FILE]" >&2; exit 2; }
AGE="" OUT=""
while [ $# -gt 0 ]; do
  case $1 in
    --age-recipient) AGE=${2:-}; shift 2 ;;
    -o) OUT=${2:-}; shift 2 ;;
    *) usage ;;
  esac
done
[[ $AGE =~ ^age1[0-9a-z]{58}$ ]] || { echo "an age recipient (age1…, 62 characters) is required" >&2; usage; }
command -v openssl >/dev/null && command -v python3 >/dev/null || { echo "openssl and python3 are required" >&2; exit 1; }
if [ -n "$OUT" ]; then
  [ -e "$OUT" ] && { echo "$OUT exists: refusing to overwrite secrets" >&2; exit 1; }
  umask 077; exec >"$OUT"
fi
hex() { openssl rand -hex "$1"; }
keyset() { printf '1:%s' "$(openssl rand -base64 32 | tr -d '\n')"; }
pem() { openssl genpkey -algorithm ed25519 2>/dev/null | sed 's/^/    /'; }
seed() {
  python3 -I -c '
import base64, os
payload = bytes([18 << 3]) + os.urandom(32)
crc = 0
for b in payload:
    crc ^= b << 8
    for _ in range(8):
        crc = ((crc << 1) ^ 0x1021) & 0xffff if crc & 0x8000 else (crc << 1) & 0xffff
print(base64.b32encode(payload + bytes([crc & 0xff, crc >> 8])).decode().rstrip("="))'
}
