"""Build the Ansible inventory (YAML) from OpenTofu outputs on stdin. Standard library only.

  tofu -chdir=infra/opentofu/envs/azure-eu output -json nodes | inventory-from-tofu.py            # scale-out profile
  tofu -chdir=infra/opentofu/envs/azure-lean output -json | inventory-from-tofu.py --lean         # lean profile (C-123)
"""
import json
import sys


def lean(out: dict) -> int:
    """Lean profile: groups app (one host) and standby (zero or one), with the variables compose_stack needs."""
    v = {k: o["value"] for k, o in out.items()}
    app, standby, hosts, repos = v["app"], v.get("standby"), v["hostnames"], v["backup_repositories"]
    app_vars = {
        "ansible_host": app["ingest_public_ip"],
        "scf_ingest_bind_ip": app["ingest_private_ip"],
        "scf_portal_bind_ip": app["portal_private_ip"],
        "scf_ingest_hostnames": hosts["ingest"],
        "scf_portal_hostname": hosts["portal"],
        "scf_status_hostname": hosts.get("status", ""),
        "scf_azure_tenant_id": app["tenant_id"],
        "scf_azure_dns_resource_group": app["dns_resource_group"],
        "scf_front_ips": [app["ingest_private_ip"], app["portal_private_ip"]],
    }
    # Host variables (they take precedence over group_vars/all.yml, which holds the scale-out defaults).
    common = {
        "ansible_user": "scfadmin",
        "scf_data_disk_device": "/dev/disk/azure/scsi1/lun0",
        "scf_vnet_cidrs": ["10.50.0.0/16"],
        "scf_backup_endpoints_prefix": app["endpoints_prefix"],
        "scf_backup_repos": [{"n": int(k[-1]), "account": r["account"], "container": r["container"]} for k, r in sorted(repos.items())],
    }
    print("# Generated by infra/ansible/scripts/inventory-from-tofu.py --lean — do not edit by hand. Keep it next to")
    print("# group_vars/ (infra/ansible/inventory.lean.yml) so group_vars/lean.sops.yaml and lean.yml are loaded.")
    print("all:")
    print("  children:")
    print("    lean:")
    print("      children:")
    print("        app:")
    print("          hosts:")
    print(f"            {app['name']}: {json.dumps(common | app_vars)}")
    print("        standby:")
    print("          hosts:" + ("" if standby else " {}"))
    if standby:
        print(f"            {standby['name']}: {json.dumps(common | {'ansible_host': standby['public_ip']})}")
    return 0


def main() -> int:
    if "--lean" in sys.argv[1:]:
        return lean(json.load(sys.stdin))
    nodes = json.load(sys.stdin)
    groups: dict[str, dict] = {}
    for name in sorted(nodes):
        n = nodes[name]
        # probe-d has no private path (outside the mesh): reached on its public address
        host = n["public_ip"] if n["class"] == "probe" else n["private_ip"]
        groups.setdefault(n["class"], {})[name] = {"ansible_host": host}
        if n.get("postgres"):
            groups.setdefault("postgres", {})[name] = {}
    print("# Generated by infra/ansible/scripts/inventory-from-tofu.py — do not edit by hand.")
    print("all:\n  vars:\n    ansible_user: scfadmin\n  children:")
    for g in sorted(groups):
        print(f"    {g}:\n      hosts:")
        for h, v in groups[g].items():
            inner = ", ".join(f"{k}: {json.dumps(val)}" for k, val in v.items())
            print(f"        {h}: {{{inner}}}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
