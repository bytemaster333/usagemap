// The analytics engine's side of the demo (mode `api` only): the dashboards answer a site's most recent days — its
// live window, scf.web_live_window_days() (C-109, wire-formats §j.6) — from Umami, not from the rollups. For those days
// (and today until now) the seed writes the same synthetic sessions and events into Umami's `session` and
// `website_event` tables of the demo websites, with the conventions our gateway uses (§c.2): a normalised path, an
// empty query string, no page title, a referrer host only, tag `v`/`s`, the declared host as hostname, no region or
// city. The same events give the rollup rows (traffic.ts), so the live part and a later `web_rollup` agree.

import type { TenantPlan } from "./plan.ts";
import { uuidFor } from "./random.ts";
import { copyField, liveWindowDays, type SeedOptions, siteHistory } from "./sql.ts";
import { DAY_MS, daySessions, dayShape, dayString } from "./traffic.ts";

export interface UmamiWebsite {
  slug: string;
  websiteId: string;
}

/** The days (UTC `YYYY-MM-DD`, oldest first) the engine must hold for a site: its live window, today included. */
export function liveDays(t: TenantPlan, o: SeedOptions, budget: number): string[] {
  const history = siteHistory(t, o);
  const L = liveWindowDays(history, budget);
  return Array.from({ length: L }, (_, i) => dayString(o.today, L - 1 - i));
}

export function buildUmamiSql(
  plan: TenantPlan[],
  o: SeedOptions,
  websites: UmamiWebsite[],
  budget: number,
): string {
  const sessions: string[] = [];
  const events: string[] = [];
  const deletes: string[] = [];
  const nowS = Math.floor(
    (o.today.getTime() - Math.floor(o.today.getTime() / DAY_MS) * DAY_MS) / 1000,
  );
  for (const w of websites) {
    const t = plan.find((x) => x.slug === w.slug);
    const site = t?.website;
    if (!t || !site) continue;
    const days = liveDays(t, o, budget);
    deletes.push(`(${q(w.websiteId)}::uuid, ${q(`${days[0]}T00:00:00Z`)}::timestamptz)`);
    for (const day of days) {
      const back = Math.round(
        (Date.UTC(o.today.getUTCFullYear(), o.today.getUTCMonth(), o.today.getUTCDate()) -
          Date.parse(`${day}T00:00:00Z`)) /
          DAY_MS,
      );
      const shape = dayShape(site, o.phrase, day, back, o.historyDays);
      const list = daySessions(site, shape, back === 0 ? nowS : 86_400);
      const dayStart = Date.parse(`${day}T00:00:00Z`);
      for (const s of list) {
        const sid = uuidFor(o.phrase, `umami-session:${site.host}:${day}:${s.index}`);
        const vid = uuidFor(o.phrase, `umami-visit:${site.host}:${day}:${s.index}`);
        const first = s.events[0]?.offsetS ?? 0;
        sessions.push(
          [
            sid,
            w.websiteId,
            s.browser,
            s.os,
            s.device,
            null,
            null,
            s.country,
            null,
            null,
            iso(dayStart + first * 1000),
          ]
            .map(copyField)
            .join("\t"),
        );
        s.events.forEach((e, k) => {
          events.push(
            [
              uuidFor(o.phrase, `umami-event:${site.host}:${day}:${s.index}:${k}`),
              w.websiteId,
              sid,
              vid,
              iso(dayStart + e.offsetS * 1000),
              e.path,
              "",
              e.referrer ? "/" : null,
              e.referrer ? "" : null,
              e.referrer,
              null,
              e.type,
              e.name,
              s.verified ? "v" : "s",
              site.host,
            ]
              .map(copyField)
              .join("\t"),
          );
        });
      }
    }
  }
  return `-- Generated by tools/demo-seed/seed.ts: synthetic DEMO events in the analytics engine for the demo websites only.
\\set ON_ERROR_STOP on
BEGIN;
CREATE TEMP TABLE demo_w (website_id uuid, since timestamptz) ON COMMIT DROP;
INSERT INTO demo_w VALUES ${deletes.length ? deletes.join(", ") : "(NULL, NULL)"};
DELETE FROM website_event e USING demo_w w WHERE e.website_id = w.website_id AND e.created_at >= w.since;
DELETE FROM session s USING demo_w w WHERE s.website_id = w.website_id AND s.created_at >= w.since
   AND NOT EXISTS (SELECT 1 FROM website_event e WHERE e.session_id = s.session_id);
COPY session (session_id, website_id, browser, os, device, screen, language, country, region, city, created_at) FROM STDIN;
${sessions.join("\n")}${sessions.length ? "\n" : ""}\\.
COPY website_event (event_id, website_id, session_id, visit_id, created_at, url_path, url_query, referrer_path,
  referrer_query, referrer_domain, page_title, event_type, event_name, tag, hostname) FROM STDIN;
${events.join("\n")}${events.length ? "\n" : ""}\\.
COMMIT;
`;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const iso = (ms: number) => new Date(ms).toISOString();
